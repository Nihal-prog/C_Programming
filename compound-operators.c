/* Compound/Short-hand assignment operators */

#include <stdio.h>

int main()
{
    int num = 9;
    printf("%d\n", num);

    num += 12;
    printf("%d\n", num);
    
    num -= 12;
    printf("%d\n", num);

    num /= 1;
    printf("%d\n", num);

    num *= 1;
    printf("%d\n", num);
    return 0;
}